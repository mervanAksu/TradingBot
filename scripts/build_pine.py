#!/usr/bin/env python3
"""Bundle pine/indicators/*.src.pine into a self-contained script by inlining the libraries it imports.

TradingView can only `import` PUBLISHED libraries; this project never publishes, so the script saved to TradingView is
the bundle. The libraries in pine/lib/ stay the source of truth.
Usage: python3 scripts/build_pine.py pine/indicators/ict_levels_viewer.src.pine
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIBS = {"ict_core": ROOT / "pine/lib/ict_core.pine", "ict_time": ROOT / "pine/lib/ict_time.pine"}


def lib_body(path: Path) -> str:
    out = []
    for ln in path.read_text().splitlines():
        if ln.startswith("//@version") or ln.startswith("library("):
            continue
        if not ln.strip() or ln.lstrip().startswith("//"):
            continue  # comments/blank lines stay in pine/lib (keeps the bundle small)
        out.append(re.sub(r"^export\s+", "", re.sub(r"\s+//[^\"]*$", "", ln)))
    return "\n".join(out)


def build(src: Path) -> Path:
    text = src.read_text()
    aliases, libs = [], []
    lines = []
    for ln in text.splitlines():
        m = re.match(r"^import\s+\S+/(\w+)/\d+\s+as\s+(\w+)", ln)
        if m:
            libs.append(m.group(1))
            aliases.append(m.group(2))
            continue
        lines.append(ln)
    body = "\n".join(lines)
    for a in aliases:
        body = re.sub(rf"\b{a}\.", "", body)
    # insert library code right after the indicator()/strategy() declaration line
    decl = re.search(r"^(indicator|strategy)\(.*$", body, re.M)
    inlined = "\n".join(
        f"// ======== inlined from pine/lib/{n}.pine (generated by scripts/build_pine.py; do not edit here)\n"
        + lib_body(LIBS[n]) for n in libs)
    body = body[: decl.end()] + "\n" + inlined + "\n// ======== end of inlined libraries\n" + body[decl.end():]
    dst = src.with_name(src.name.replace(".src.pine", ".pine"))
    dst.write_text(body.rstrip() + "\n")
    return dst


if __name__ == "__main__":
    for a in sys.argv[1:]:
        print(build(Path(a)))
